CREATE TABLE task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    title VARCHAR(120) NOT NULL,
    description VARCHAR(1000) NOT NULL,
    status VARCHAR(16) NOT NULL,
    priority INTEGER,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_task_owner FOREIGN KEY (owner_id) REFERENCES app_user (id) ON DELETE CASCADE,
    CONSTRAINT ck_task_status CHECK (status IN ('ACTIVE', 'COMPLETED')),
    CONSTRAINT ck_task_lifecycle CHECK (
        (status = 'ACTIVE' AND priority IS NOT NULL AND priority > 0 AND completed_at IS NULL)
        OR (status = 'COMPLETED' AND priority IS NULL AND completed_at IS NOT NULL)
    )
);

CREATE INDEX task_owner_status_priority_ix ON task (owner_id, status, priority);
CREATE INDEX task_owner_status_completed_ix ON task (owner_id, status, completed_at);
